  /// 取一条文案；`{0}` 这类占位符用 [args] 填充。
  static String t(String key, [List<Object?> args = const <Object?>[]]) {
    final table = _tables[language.value] ?? _tables['zh-CN']!;
    var text = table[key] ?? _tables['zh-CN']![key] ?? key;
    for (var i = 0; i < args.length; i++) {
      text = text.replaceAll('{$i}', '${args[i]}');
    }
    return text;
  }

  /// 把后端语言设置（auto / zh-CN / en）解析成实际语言。
  static String resolve(String? preference) {
    if (preference != null && preference.isNotEmpty && preference != 'auto') {
      return preference.startsWith('en') ? 'en' : 'zh-CN';
    }
    final locale = WidgetsBinding.instance.platformDispatcher.locale;
    return locale.languageCode == 'zh' ? 'zh-CN' : 'en';
  }

  static void setLanguage(String code) {
    final resolved = resolve(code);
    if (language.value != resolved) language.value = resolved;
  }
}

/// 便捷取词：`T('nav.home')`。
String T(String key, [List<Object?> args = const <Object?>[]]) => I18n.t(key, args);
